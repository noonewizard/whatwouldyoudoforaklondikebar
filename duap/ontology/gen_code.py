#!/usr/bin/env python3
"""Generate typed taxonomy code for every DUAP SDK from the ontology JSON.

One ontology, four languages. Divergence between SDK taxonomies would be an
interoperability break that no amount of testing on one side would catch, so
the enums are never hand-written. CI runs this with --check.
"""
import json, pathlib, sys, hashlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
ONT = json.loads((ROOT / "ontology" / "duap-ontology-v1.json").read_text())
ONT_BYTES = (ROOT / "ontology" / "duap-ontology-v1.json").read_bytes()
ONT_HASH = hashlib.sha256(ONT_BYTES).hexdigest()

BANNER_LINES = [
    "DO NOT EDIT. Generated by ontology/gen_code.py from",
    "ontology/duap-ontology-v1.json (sha256 " + ONT_HASH[:32] + "...).",
    "Edit the ontology and regenerate; CI fails if this file is stale.",
]


def variant(code):
    return "".join(p.capitalize() for part in code.split(".") for p in part.split("_"))


def snake(code):
    return code.replace(".", "_").replace("-", "_")


def screaming(code):
    return snake(code).upper()


def esc(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"')


