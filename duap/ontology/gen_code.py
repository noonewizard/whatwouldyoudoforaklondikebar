def rust_enum(name, items, doc, extra_methods=""):
    out = [f"/// {doc}"]
    out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]")
    out.append('#[serde(try_from = "String", into = "String")]')
    out.append(f"pub enum {name} {{")
    for it in items:
        d = it.get("name", it["code"])
        out.append(f"    /// `{it['code']}` -- {d}")
        if it.get("notes"):
            out.append(f"    ///")
            out.append(f"    /// {esc(it['notes'])}")
        out.append(f"    {variant(it['code'])},")
    out.append("}")
    out.append("")
    out.append(f"impl {name} {{")
    out.append(f"    /// Every registered {name} value, in ontology order.")
    out.append(f"    pub const ALL: [{name}; {len(items)}] = [")
    for it in items:
        out.append(f"        {name}::{variant(it['code'])},")
    out.append("    ];")
    out.append("")
    out.append("    /// The ontology code.")
    out.append("    pub const fn code(self) -> &'static str {")
    out.append("        match self {")
    for it in items:
        out.append(f'            {name}::{variant(it["code"])} => "{it["code"]}",')
    out.append("        }")
    out.append("    }")
    out.append("")
    out.append("    /// Human-readable label.")
    out.append("    pub const fn label(self) -> &'static str {")
    out.append("        match self {")
    for it in items:
        out.append(f'            {name}::{variant(it["code"])} => "{esc(it.get("name", it["code"]))}",')
    out.append("        }")
    out.append("    }")
    out.append("")
    out.append("    /// Parse an ontology code.")
    out.append("    pub fn parse(s: &str) -> Result<Self, TaxonomyError> {")
    out.append("        match s {")
    for it in items:
        out.append(f'            "{it["code"]}" => Ok({name}::{variant(it["code"])}),')
    out.append(f'            other => Err(TaxonomyError::UnknownCode {{ kind: "{name}", code: other.to_owned() }}),')
    out.append("        }")
    out.append("    }")
    out.append(extra_methods)
    out.append("}")
    out.append("")
    out.append(f"impl std::fmt::Display for {name} {{")
    out.append("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {")
    out.append("        f.write_str(self.code())")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append(f"impl std::str::FromStr for {name} {{")
    out.append("    type Err = TaxonomyError;")
    out.append("    fn from_str(s: &str) -> Result<Self, TaxonomyError> { Self::parse(s) }")
    out.append("}")
    out.append("")
    out.append(f"impl TryFrom<String> for {name} {{")
    out.append("    type Error = TaxonomyError;")
    out.append("    fn try_from(s: String) -> Result<Self, TaxonomyError> { Self::parse(&s) }")
    out.append("}")
    out.append("")
    out.append(f"impl From<{name}> for String {{")
    out.append(f"    fn from(v: {name}) -> String {{ v.code().to_owned() }}")
    out.append("}")
    out.append("")
    return "\n".join(out)


def gen_rust():
    L = []
    for b in BANNER_LINES:
        L.append(f"// {b}")
    L.append("")
    L.append("//! Typed DUAP taxonomy: data classes, operations, purposes, units,")
    L.append("//! collection methods, sensitivity tiers, regimes and lawful bases.")
    L.append("//!")
    L.append("//! STATUS: PRODUCTION (generated).")
    L.append("")
    L.append("#![allow(clippy::match_like_matches_macro)]")
    L.append("")
    L.append("use serde::{Deserialize, Serialize};")
    L.append("use crate::error::TaxonomyError;")
    L.append("")
    L.append(f'/// Version of the ontology these definitions were generated from.')
    L.append(f'pub const ONTOLOGY_VERSION: &str = "{ONT["ontology_version"]}";')
    L.append(f'/// SHA-256 of the ontology document, for cross-implementation checks.')
    L.append(f'pub const ONTOLOGY_SHA256: &str = "{ONT_HASH}";')
    L.append("")

    # sensitivity tier
    tiers = ONT["sensitivity_tiers"]
    extra = ["", "    /// Ordinal rank; higher means more sensitive.",
             "    pub const fn rank(self) -> u8 {", "        match self {"]
    for t in tiers:
        extra.append(f"            SensitivityTier::{variant(t['code'])} => {t['rank']},")
    extra += ["        }", "    }"]
    L.append(rust_enum("SensitivityTier", tiers,
                       "How much harm disclosure of this data would do to the subject.",
                       "\n".join(extra)))

    # data classes
    dcs = ONT["data_classes"]
    extra = ["", "    /// Default sensitivity tier for this class.",
             "    pub const fn sensitivity(self) -> SensitivityTier {", "        match self {"]
    for d in dcs:
        extra.append(f"            DataClass::{variant(d['code'])} => SensitivityTier::{variant(d['sensitivity'])},")
    extra += ["        }", "    }", "",
              "    /// Prior for the re-identification risk of one record of this class,",
              "    /// on a 0-100 scale. A parameter of the valuation model, not a",
              "    /// measurement; see `VALUATION.md` for the calibration procedure.",
              "    pub const fn reid_risk(self) -> u8 {", "        match self {"]
    for d in dcs:
        extra.append(f"            DataClass::{variant(d['code'])} => {d['reid_risk']},")
    extra += ["        }", "    }", "",
              "    /// Regime-specific special-category tags asserted for this class.",
              "    pub const fn special_categories(self) -> &'static [&'static str] {",
              "        match self {"]
    for d in dcs:
        arr = ", ".join(f'"{s}"' for s in d["special_category"])
        extra.append(f"            DataClass::{variant(d['code'])} => &[{arr}],")
    extra += ["        }", "    }", "",
              "    /// Whether any regime tags this class as a special category.",
              "    pub const fn is_special_category(self) -> bool {",
              "        !self.special_categories().is_empty()", "    }",
              "",
              "    /// The dotted namespace prefix, e.g. `location` for `location.precise`.",
              "    pub fn namespace(self) -> &'static str {",
              "        let c = self.code();",
              "        match c.find('.') { Some(i) => &c[..i], None => c }",
              "    }"]
    L.append(rust_enum("DataClass", dcs, "A class of data in the DUAP taxonomy.", "\n".join(extra)))

    # collection methods
    cms = ONT["collection_methods"]
    extra = ["", "    /// Whether a data subject can in principle detect this collection",
             "    /// locally. Used by the participant dashboard to flag collection the",
             "    /// subject has no way of observing without the protocol.",
             "    pub const fn subject_observable(self) -> bool {", "        match self {"]
    for c in cms:
        extra.append(f"            CollectionMethod::{variant(c['code'])} => {str(c['subject_observable']).lower()},")
    extra += ["        }", "    }"]
    L.append(rust_enum("CollectionMethod", cms, "How data was obtained.", "\n".join(extra)))

    # units
    units = ONT["units"]
    extra = ["", "    /// Whether quantities in this unit may be summed across events.",
             "    ///",
             "    /// Non-additive units (attribution shares) must be combined with the",
             "    /// scope-aware rules in `duap-valuation`, never added.",
             "    pub const fn additive(self) -> bool {", "        match self {"]
    for u in units:
        extra.append(f"            Unit::{variant(u['code'])} => {str(u['additive']).lower()},")
    extra += ["        }", "    }"]
    L.append(rust_enum("Unit", units, "A measurement unit for metered quantities.", "\n".join(extra)))

    # operations
    ops = ONT["operations"]
    fams = sorted({o["family"] for o in ops})
    L.append("/// Top-level operation families.")
    L.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]")
    L.append('#[serde(rename_all = "snake_case")]')
    L.append("pub enum OperationFamily {")
    for f in fams:
        L.append(f"    {variant(f)},")
    L.append("}")
    L.append("")
    L.append("impl OperationFamily {")
    L.append("    pub const fn code(self) -> &'static str {")
    L.append("        match self {")
    for f in fams:
        L.append(f'            OperationFamily::{variant(f)} => "{f}",')
    L.append("        }")
    L.append("    }")
    L.append("}")
    L.append("")
    extra = ["", "    /// Operation family.",
             "    pub const fn family(self) -> OperationFamily {", "        match self {"]
    for o in ops:
        extra.append(f"            Operation::{variant(o['code'])} => OperationFamily::{variant(o['family'])},")
    extra += ["        }", "    }", "",
              "    /// The unit this operation is naturally metered in.",
              "    pub const fn meter(self) -> Unit {", "        match self {"]
    for o in ops:
        extra.append(f"            Operation::{variant(o['code'])} => Unit::{variant(o['meter'])},")
    extra += ["        }", "    }", "",
              "    /// Whether the operation can produce a derived object whose rights",
              "    /// must be propagated through the provenance graph.",
              "    pub const fn derives(self) -> bool {", "        match self {"]
    for o in ops:
        extra.append(f"            Operation::{variant(o['code'])} => {str(o['derives']).lower()},")
    extra += ["        }", "    }"]
    L.append(rust_enum("Operation", ops, "An operation performed on data.", "\n".join(extra)))

    # purposes with lattice
    pus = ONT["purposes"]
    extra = ["", "    /// The parent purpose in the lattice, if any.",
             "    pub const fn parent(self) -> Option<Purpose> {", "        match self {"]
    for p in pus:
        if p["parent"]:
            extra.append(f"            Purpose::{variant(p['code'])} => Some(Purpose::{variant(p['parent'])}),")
        else:
            extra.append(f"            Purpose::{variant(p['code'])} => None,")
    extra += ["        }", "    }", "",
              "    /// Whether this purpose is a commercial exploitation of the data.",
              "    /// Drives the default pricing model and several policy defaults.",
              "    pub const fn commercial(self) -> bool {", "        match self {"]
    for p in pus:
        extra.append(f"            Purpose::{variant(p['code'])} => {str(p['commercial']).lower()},")
    extra += ["        }", "    }", "",
              "    /// Whether `self` is `other` or an ancestor of it.",
              "    ///",
              "    /// Purpose limitation is decided by this relation. A grant for",
              "    /// `marketing` covers `marketing.advertising.behavioral`; a grant for",
              "    /// `marketing.advertising.contextual` does not.",
              "    pub fn covers(self, other: Purpose) -> bool {",
              "        let mut cur = Some(other);",
              "        while let Some(p) = cur {",
              "            if p == self { return true; }",
              "            cur = p.parent();",
              "        }",
              "        false",
              "    }",
              "",
              "    /// Distance to the root of the lattice.",
              "    pub fn depth(self) -> usize {",
              "        let mut d = 0; let mut cur = self.parent();",
              "        while let Some(p) = cur { d += 1; cur = p.parent(); }",
              "        d",
              "    }"]
    L.append(rust_enum("Purpose", pus, "A purpose of processing, forming a lattice.", "\n".join(extra)))

    L.append(rust_enum("Regime", ONT["regimes"],
                       "A regulatory regime tag. A recording category, not a legal determination."))
    L.append(rust_enum("LawfulBasis", ONT["lawful_bases"],
                       "A lawful-basis assertion made by the controller."))
    return "\n".join(L) + "\n"


