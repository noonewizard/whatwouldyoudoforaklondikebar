def gen_go():
    L = []
    for b in BANNER_LINES:
        L.append("// " + b)
    L.append("")
    L.append("package taxonomy")
    L.append("")
    L.append(f'const OntologyVersion = "{ONT["ontology_version"]}"')
    L.append(f'const OntologySHA256 = "{ONT_HASH}"')
    L.append("")

    def gotype(name, items, doc):
        out = [f"// {name} is {doc}", f"type {name} string", "", "const ("]
        for it in items:
            out.append(f'\t{name}{variant(it["code"])} {name} = "{it["code"]}"')
        out.append(")")
        out.append("")
        out.append(f"// All{name}s lists every registered value, in ontology order.")
        out.append(f"var All{name}s = []{name}{{")
        for it in items:
            out.append(f'\t{name}{variant(it["code"])},')
        out.append("}")
        out.append("")
        out.append(f"// Valid reports whether v is a registered {name}.")
        out.append(f"func (v {name}) Valid() bool {{")
        out.append(f"\t_, ok := valid{name}[v]")
        out.append("\treturn ok")
        out.append("}")
        out.append("")
        out.append(f"var valid{name} = func() map[{name}]struct{{}} {{")
        out.append(f"\tm := make(map[{name}]struct{{}}, len(All{name}s))")
        out.append(f"\tfor _, v := range All{name}s {{")
        out.append("\t\tm[v] = struct{}{}")
        out.append("\t}")
        out.append("\treturn m")
        out.append("}()")
        out.append("")
        return "\n".join(out)

