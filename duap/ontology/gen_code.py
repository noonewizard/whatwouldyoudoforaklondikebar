def gen_typescript():
    L = ["/**"]
    for b in BANNER_LINES:
        L.append(" * " + b)
    L.append(" */")
    L.append("")
    L.append(f'export const ONTOLOGY_VERSION = "{ONT["ontology_version"]}";')
    L.append(f'export const ONTOLOGY_SHA256 = "{ONT_HASH}";')
    L.append("")

    def tsunion(name, items, doc):
        out = [f"/** {doc} */", f"export type {name} ="]
        for i, it in enumerate(items):
            sep = ";" if i == len(items) - 1 else ""
            out.append(f'  | "{it["code"]}"{sep}')
        out.append("")
        out.append(f"export const {screaming(name)}_ALL: readonly {name}[] = [")
        for it in items:
            out.append(f'  "{it["code"]}",')
        out.append("];")
        out.append("")
        return "\n".join(out)

    L.append(tsunion("SensitivityTier", ONT["sensitivity_tiers"], "Sensitivity tiers."))
    L.append(tsunion("DataClass", ONT["data_classes"], "Data classes."))
